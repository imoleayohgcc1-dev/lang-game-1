  public getLessons(languageCode: LanguageCode, lessonNumber: number = 1): LearningItem[] {
    const list = this.lessonsByLang[languageCode] || this.lessonsByLang['zh-CN'];
    return list.filter((item) => item.lessonNumber === lessonNumber);
  }

  public getNextChallengeItem(progress: LearningProgress): LearningItem {
    const list = this.lessonsByLang[progress.targetLanguageCode] || this.lessonsByLang['zh-CN'];

    // Find an unencountered or uncompleted word first
    const uncompleted = list.find((item) => !progress.wordsCompleted.includes(item.id));
    if (uncompleted) return uncompleted;

    // If all completed in current lesson, pick least recently completed
    const unencountered = list.find((item) => !progress.wordsEncountered.includes(item.id));
    if (unencountered) return unencountered;

    // Loop through lesson items
    const index = progress.totalChallengesCompleted % list.length;
    return list[index];
  }

  public getItemById(id: string): LearningItem | undefined {
    for (const code in this.lessonsByLang) {
      const found = this.lessonsByLang[code as LanguageCode].find((item) => item.id === id);
      if (found) return found;
    }
    return undefined;
  }
