  /**
   * Retrieves a lesson by ID or by language code and lesson number.
   */
  public static getLessonById(lessonId: string): LessonDefinition | undefined {
    for (const lang in this.lessonDatabase) {
      const found = this.lessonDatabase[lang as LanguageCode].find((l) => l.lessonId === lessonId);
      if (found) return found;
    }
    return undefined;
  }

  /**
   * Retrieves or generates a lesson by number.
   * If lesson number exceeds pre-authored catalog, dynamically generates a procedural lesson.
   * This satisfies Requirement 3: "Do not permanently lock the game to only five lessons."
   */
  public static getLesson(languageCode: LanguageCode, lessonNumber: number = 1): LessonDefinition {
    const list = this.lessonDatabase[languageCode] || this.lessonDatabase['zh-CN'];
    const existing = list.find((l) => l.lessonNumber === lessonNumber);
    if (existing) {
      return existing;
    }

    // Generate procedural lesson for higher numbers
    return this.generateProceduralLesson(languageCode, lessonNumber);
  }

  public static getAllLessonsForLanguage(languageCode: LanguageCode): LessonDefinition[] {
    const curated = this.lessonDatabase[languageCode] || [];
    const list = [...curated];
    while (list.length < 5) {
      list.push(this.generateProceduralLesson(languageCode, list.length + 1));
    }
    return list;
  }

  public static getLessonsForLanguage(languageCode: LanguageCode): LessonDefinition[] {
    return this.getAllLessonsForLanguage(languageCode);
  }

